    val disabledOnPrimary: Color,
    val disabledOnSurface: Color,
    val disabledOnSecondaryVariant: Color,
    val sliderBackground: Color,
    val sliderKeyPoint: Color,
    val sliderKeyPointForeground: Color,
)

